"""Turn a folder of your own, authorised essays into a benchmark manifest.

Put the essays and a `metadata.csv` in one folder inside the git-ignored
`experiments/benchmark-private/`, then run (from the repository root):

    python scripts/build_manifest.py experiments/benchmark-private/my-essays

`metadata.csv` (UTF-8, Excel's "CSV UTF-8" works) needs one row per file:

    file,lang,label,group_id,source,license,writer_group,domain
    essays/0001-human.txt,en,human,0001,Class of 2026 submissions,Written consent for local evaluation only,non_native,argumentative
    essays/0001-ai.txt,en,ai,0001,Same prompt rewritten by a generator,Generated by the evaluator,generated,argumentative

Required: file, lang (en/zh), label (human/ai/mixed), source. Optional: group_id (versions of
the same original MUST share it; defaults to the file name), split (calibration/test), license,
source_url, writer_group, domain, generated_model, training_overlap
(unknown/possible/excluded) and training_overlap_evidence.

Rows without a split are assigned one per group, deterministically from the group id and
`--seed`, so every version of an original lands in the same split. Each file's SHA-256 is
recorded. Nothing is uploaded; the manifest only lists relative file paths.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import sys
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
PRIVATE_ROOT = REPO_ROOT / "experiments" / "benchmark-private"
LANGS = {"en", "zh"}
LABELS = {"human", "ai", "mixed"}
SPLITS = {"calibration", "test"}
SUFFIXES = {".txt", ".docx", ".pdf"}
OVERLAP = {"unknown", "possible", "excluded"}
OPTIONAL = (
    "license",
    "source_url",
    "writer_group",
    "domain",
    "generated_model",
    "training_overlap_evidence",
)


def assign_split(group_id: str, seed: str, calibration_share: float) -> str:
    digest = hashlib.sha256(f"{seed}\0{group_id}".encode("utf-8")).digest()
    position = int.from_bytes(digest[:8], "big") / 2**64
    return "calibration" if position < calibration_share else "test"


def build_rows(
    folder: Path, metadata: list[dict], seed: str, calibration_share: float
) -> list[dict]:
    root = folder.resolve()
    rows: list[dict] = []
    seen_ids: set[str] = set()
    by_digest: dict[str, str] = {}
    group_split: dict[str, str] = {}
    for number, raw in enumerate(metadata, 2):  # line 1 is the header
        meta = {k.strip(): (v or "").strip() for k, v in raw.items() if k}
        where = f"metadata.csv line {number}"
        for key in ("file", "lang", "label", "source"):
            if not meta.get(key):
                raise ValueError(f"{where}: missing {key}")
        if meta["lang"] not in LANGS:
            raise ValueError(f"{where}: lang must be en or zh")
        if meta["label"] not in LABELS:
            raise ValueError(f"{where}: label must be human, ai or mixed")
        path = (root / meta["file"]).resolve()
        if not path.is_relative_to(root) or not path.is_file():
            raise ValueError(f"{where}: file not found inside the folder: {meta['file']}")
        if path.suffix.lower() not in SUFFIXES:
            raise ValueError(f"{where}: only .txt, .docx and text PDF files are supported")
        relative = path.relative_to(root).as_posix()
        sample_id = Path(relative).with_suffix("").as_posix().replace("/", "-")
        if sample_id in seen_ids:
            raise ValueError(f"{where}: two files map to the same id {sample_id}")
        seen_ids.add(sample_id)
        group_id = meta.get("group_id") or sample_id
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if digest in by_digest:
            raise ValueError(f"{where}: same content as {by_digest[digest]}; remove the duplicate")
        by_digest[digest] = relative
        split = meta.get("split") or assign_split(group_id, seed, calibration_share)
        if split not in SPLITS:
            raise ValueError(f"{where}: split must be calibration or test")
        if group_split.setdefault(group_id, split) != split:
            raise ValueError(
                f"{where}: group {group_id} is in both calibration and test; "
                "all versions of one original must share a split"
            )
        overlap = meta.get("training_overlap") or "unknown"
        if overlap not in OVERLAP:
            raise ValueError(f"{where}: training_overlap must be unknown, possible or excluded")
        if overlap == "excluded" and not meta.get("training_overlap_evidence"):
            raise ValueError(f"{where}: training_overlap=excluded needs training_overlap_evidence")
        row = {
            "id": sample_id,
            "file": relative,
            "lang": meta["lang"],
            "label": meta["label"],
            "source": meta["source"],
            "group_id": group_id,
            "split": split,
            "training_overlap": overlap,
            "text_sha256": digest,
        }
        row.update({key: meta[key] for key in OPTIONAL if meta.get(key)})
        rows.append(row)
    if not rows:
        raise ValueError("metadata.csv has no rows")
    return rows


def describe(rows: list[dict]) -> str:
    counts = Counter((r["lang"], r["split"], r["label"]) for r in rows)
    groups = Counter(
        (r["lang"], r["split"])
        for r in {(r["lang"], r["split"], r["group_id"]): r for r in rows}.values()
    )
    lines = []
    for lang in sorted({r["lang"] for r in rows}):
        for split in ("calibration", "test"):
            parts = ", ".join(f"{label} {counts[(lang, split, label)]}" for label in sorted(LABELS))
            lines.append(f"  {lang} {split}: {parts}; groups {groups[(lang, split)]}")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("folder", type=Path, help="Folder holding metadata.csv and the essay files")
    parser.add_argument("--metadata", default="metadata.csv", help="CSV file inside the folder")
    parser.add_argument("--seed", default="20261104", help="Seed for assigning splits per group")
    parser.add_argument(
        "--calibration-share",
        type=float,
        default=0.5,
        help="Share of groups (without an explicit split) that go to calibration",
    )
    args = parser.parse_args()
    folder = args.folder.resolve()
    if not folder.is_relative_to(PRIVATE_ROOT.resolve()):
        parser.error(
            "the folder must be inside experiments/benchmark-private/ (git-ignored), "
            "so private essays are never committed"
        )
    if not 0 < args.calibration_share < 1:
        parser.error("--calibration-share must be between 0 and 1")
    with (folder / args.metadata).open(encoding="utf-8-sig", newline="") as stream:
        metadata = list(csv.DictReader(stream))
    try:
        rows = build_rows(folder, metadata, args.seed, args.calibration_share)
    except ValueError as error:
        sys.exit(f"error: {error}")
    out = folder / "manifest.jsonl"
    out.write_text(
        "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8"
    )
    sys.path.insert(0, str(REPO_ROOT / "backend"))
    from benchmark import load_manifest  # same checks the evaluation run will apply

    load_manifest(out)
    print(f"Wrote {out} ({len(rows)} files)\n{describe(rows)}")


if __name__ == "__main__":
    main()
